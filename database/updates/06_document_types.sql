-- 1. Crear tabla sys_document_types
CREATE TABLE IF NOT EXISTS sys_document_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE, -- ej. Factura, Recibo, Proforma
    prefix VARCHAR(10) NOT NULL, -- ej. FAC, REC, PROF
    establishment VARCHAR(3) NOT NULL DEFAULT '001', -- ej. 001
    emission_point VARCHAR(3) NOT NULL DEFAULT '001', -- ej. 001
    current_sequence BIGINT NOT NULL DEFAULT 0, -- Se incrementará en cada transacción
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

