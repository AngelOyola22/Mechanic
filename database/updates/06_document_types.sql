-- 6. Función RPC para obtener el siguiente secuencial de forma atómica y segura
CREATE OR REPLACE FUNCTION fn_get_next_document_number(p_document_type_id BIGINT)
RETURNS VARCHAR AS $$
DECLARE
    v_prefix VARCHAR;
    v_establishment VARCHAR;
    v_emission_point VARCHAR;
    v_next_seq BIGINT;
    v_doc_number VARCHAR;
BEGIN
    -- Update and return the values atomically
    UPDATE sys_document_types 
    SET current_sequence = current_sequence + 1
    WHERE id = p_document_type_id AND is_active = true
    RETURNING prefix, establishment, emission_point, current_sequence 
    INTO v_prefix, v_establishment, v_emission_point, v_next_seq;

    IF v_prefix IS NULL THEN
        RAISE EXCEPTION 'Document type not found or inactive';
    END IF;

    -- Format: PREFIX-EST-EMI-SEQUENCE (e.g. FAC-001-001-000000001)
    v_doc_number := v_prefix || '-' || v_establishment || '-' || v_emission_point || '-' || LPAD(v_next_seq::VARCHAR, 9, '0');
    
    RETURN v_doc_number;
END;
$$ LANGUAGE plpgsql;
