-- 1. Crear tabla tra_oil_changes si no existe
CREATE TABLE IF NOT EXISTS tra_oil_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES tra_sales(id) ON DELETE SET NULL,
    client_id BIGINT NOT NULL REFERENCES cat_clients(id) ON DELETE CASCADE,
    vehicle_plate VARCHAR(20) NOT NULL,
    vehicle_brand VARCHAR(100),
    vehicle_model VARCHAR(100),
    vehicle_year INT,
    current_mileage INT NOT NULL,
    next_change_mileage INT NOT NULL,
    oil_type VARCHAR(100),
    service_date TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    notes TEXT,
    status VARCHAR(30) DEFAULT 'ACTIVE', -- 'ACTIVE', 'NOTIFIED', 'COMPLETED'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Políticas RLS para tra_oil_changes
ALTER TABLE tra_oil_changes ENABLE ROW LEVEL SECURITY;

DO $$ 
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'tra_oil_changes' AND policyname = 'Permitir todo a usuarios en tra_oil_changes'
    ) THEN
        CREATE POLICY "Permitir todo a usuarios en tra_oil_changes" ON tra_oil_changes
            FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;

