-- 1. Crear tabla cat_measurement_units (Unidades de Medida)
CREATE TABLE IF NOT EXISTS cat_measurement_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    abbreviation VARCHAR(10) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE
);

-- 2. Crear tabla cat_parts_brands (Marcas de Repuestos/Insumos)
CREATE TABLE IF NOT EXISTS cat_parts_brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN DEFAULT TRUE
);

-- 3. Modificar tabla cat_products para relacionarla
ALTER TABLE cat_products ADD COLUMN IF NOT EXISTS unit_id BIGINT REFERENCES cat_measurement_units(id);
ALTER TABLE cat_products ADD COLUMN IF NOT EXISTS brand_id BIGINT REFERENCES cat_parts_brands(id);

-- 4. Crear Pantallas en el Módulo de Catálogos (module_id = 2)
INSERT INTO seg_screens (id, module_id, name, route, icon) VALUES
(24, 2, 'Marcas de Repuestos', '/catalogs/parts-brands', 'Tag'),
(25, 2, 'Unidades de Medida', '/catalogs/measurement-units', 'Scale')
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, route = EXCLUDED.route, icon = EXCLUDED.icon;

SELECT setval(pg_get_serial_sequence('seg_screens', 'id'), coalesce(max(id), 0) + 1, false) FROM seg_screens;

