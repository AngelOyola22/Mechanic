-- 1. Mejorar tabla de Clientes para soportar Proveedores
ALTER TABLE cat_clients ADD COLUMN IF NOT EXISTS is_supplier BOOLEAN DEFAULT FALSE;
ALTER TABLE cat_clients ADD COLUMN IF NOT EXISTS is_customer BOOLEAN DEFAULT TRUE;

-- 2. Crear Tabla de Sucursales (Branches)
CREATE TABLE IF NOT EXISTS cat_branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    address TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 3. Conectar Bodegas a Sucursales
ALTER TABLE cat_warehouses ADD COLUMN IF NOT EXISTS branch_id BIGINT REFERENCES cat_branches(id) ON DELETE CASCADE;

-- 4. Conectar Compras a Proveedores y Bodegas
ALTER TABLE tra_purchases ADD COLUMN IF NOT EXISTS supplier_id BIGINT REFERENCES cat_clients(id);
ALTER TABLE tra_purchases ADD COLUMN IF NOT EXISTS warehouse_id BIGINT REFERENCES cat_warehouses(id);

-- 5. Conectar Ventas a Sucursales
ALTER TABLE tra_sales ADD COLUMN IF NOT EXISTS branch_id BIGINT REFERENCES cat_branches(id);

-- ==========================================
-- INYECCIÓN EN EL SISTEMA DE SEGURIDAD
