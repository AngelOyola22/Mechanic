-- 1. Tabla de Bodegas
CREATE TABLE IF NOT EXISTS cat_warehouses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    location TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 2. Tabla de Stock por Bodega (Cruce Producto-Bodega)
CREATE TABLE IF NOT EXISTS tra_product_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES cat_products(id) ON DELETE CASCADE,
    warehouse_id BIGINT REFERENCES cat_warehouses(id) ON DELETE CASCADE,
    quantity INT NOT NULL DEFAULT 0,
    last_updated TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    UNIQUE(product_id, warehouse_id)
);

-- 3. Modificación del Kardex para incluir Bodegas
-- Si la columna ya existe en otra corrida, este paso fallaría, 
-- por lo que en Supabase se usa ADD COLUMN IF NOT EXISTS si la versión lo soporta,
-- o simplemente se añade la columna:
ALTER TABLE tra_kardex ADD COLUMN warehouse_id BIGINT REFERENCES cat_warehouses(id);

