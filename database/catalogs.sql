-- Estructura exacta solicitada para el sistema Mechanic

-- 1. Clientes
CREATE TABLE IF NOT EXISTS cat_clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id VARCHAR(50) UNIQUE NOT NULL, 
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(50),
    address TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 2. Productos 
-- (Asume que cat_product_types y cat_taxes ya existen según seed.sql)
CREATE TABLE IF NOT EXISTS cat_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(100) UNIQUE NOT NULL,
    type_id BIGINT REFERENCES cat_product_types(id),
    tax_id BIGINT REFERENCES cat_taxes(id),
    name VARCHAR(255) NOT NULL,
    description TEXT,
    base_price DECIMAL(12,2) NOT NULL DEFAULT 0,
    current_stock INT NOT NULL DEFAULT 0, 
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 3. Ingreso de Mercadería (Compras)
CREATE TABLE IF NOT EXISTS tra_purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES seg_users(id),
    invoice_number VARCHAR(100),
    total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    status VARCHAR(50) DEFAULT 'COMPLETED',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 4. Detalle de Ingreso de Mercadería
CREATE TABLE IF NOT EXISTS tra_purchase_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT REFERENCES tra_purchases(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES cat_products(id),
    quantity INT NOT NULL,
    unit_cost DECIMAL(12,2) NOT NULL
);

-- 5. Ventas
CREATE TABLE IF NOT EXISTS tra_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES cat_clients(id),
    user_id BIGINT REFERENCES seg_users(id),
    invoice_number VARCHAR(100) UNIQUE,
    subtotal DECIMAL(12,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    status VARCHAR(50) DEFAULT 'COMPLETED',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 6. Detalle de Ventas
CREATE TABLE IF NOT EXISTS tra_sale_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES tra_sales(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES cat_products(id),
    quantity INT NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    tax_applied DECIMAL(12,2) NOT NULL 
);

-- 7. KARDEX 
CREATE TABLE IF NOT EXISTS tra_kardex (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES cat_products(id) ON DELETE CASCADE,
    movement_type_id BIGINT REFERENCES tra_movement_types(id),
    reference_id BIGINT, 
    quantity INT NOT NULL, 
    stock_balance INT NOT NULL, 
    user_id BIGINT REFERENCES seg_users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

